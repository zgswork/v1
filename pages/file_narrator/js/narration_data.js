/* ============================================================
* 内容解说数据文件  pdf_narrator V0.5.0
* ------------------------------------------------------------
* 使用说明:
* 1. pdfs 数组 = 页面顶部「文件」下拉列表的全部条目（**各种文件格式都可以**）,
*    数组顺序即下拉列表顺序；默认选中 defaultPdf 指定的条目（留空则取第 1 个）。
* 2. 每个条目字段:
*      id         唯一标识（字母数字,勿重复）
*      name       下拉列表中显示的名称
*      type       ★ 文件格式,见第 2.1 条；可省略（此时按 url 扩展名自动判定）
*      url        文件路径（相对本页目录,如 file/xxx.pdf；图片条目改在每页写 src）
*      basePoint  ★ 该条目的标准基点（比例坐标 x,y,0~1；x 从左到右,y 从上到下）
*      pages      每一页的触点数据,数组下标 = 页码 - 1（图片条目每页另带 src,见第 9 条）
* 2.1 type 取值（V0.5.0 起共 9 种,省略时按扩展名自动判定）:
*      "pdf"                              PDF（用 PDF.js 渲染,页数取自文件本身）
*      "image"  png/jpg/jpeg/gif/webp/bmp/svg  图片（直接用 <img> 显示）
*      "text"   txt/md/csv/log/ini/json…  纯文本（自动分页排版后绘制）
*      "docx"   docx/docm                Word 文档（解包读取正文,自动分页）
*      "doc"    doc                     旧版 Word（二进制,尽力提取文字；不足时给提示页）
*      "pptx"   pptx/pptm                PPT（一张幻灯片 = 一页）
*      "ppt"    ppt                     旧版 PPT（同上,尽力提取）
*      "dxf"    dxf                     文本型 DXF 图形（解析实体后绘制）
*      "dwg"    dwg                     DWG（浏览器无法解析二进制,给出转换指引页）
*    说明:真实格式最终还会按「文件签名」再判一次（.doc 其实是 docx、.dwg 其实是 DXF
*    都会自动走正确路径）；TXT 支持用换页符 \f（或单独一行 ---）显式分页。
* 3. 触点位置 = 该条目的 basePoint + 触点自身 x/y 偏移（同样为页面比例,可正可负）,
*    程序自动换算像素,无需关心分辨率；换图只需改 basePoint 一处。
*    例:basePoint 取页面中心 (0.5, 0.5),某触点 x = -0.3 → 显示在页面横向 20% 处。
* 4. 新增 / 删减触点:在对应页的 hotspots 数组里增删对象即可；
*    页数不足时 pages 数组会自动跳过（无热点的页正常翻页）。
* 5. defaultTemplate:默认声音模板 id,可选 "male"（男播音）/ "female"（女播音）
*    / "loli"（萝莉音）/ "uncle"（大叔音）。V0.2.0 起默认为男播音。
*    defaultVoiceOn（V0.5.0）:是否默认勾选「语音说明」,默认 true；设为 false 则默认关闭。
* 6. 自动巡讲（V0.1.0 起）:逐触点解说,语音结束后 2 秒进入下一个,
*    页内解说完毕自动翻页（间隔常量 TOUR_GAP 在 js/main.js 中）。
*    ★ V0.5.0:翻页严格发生在本页**最后一段语音播放完毕**之后。
* 7. 定位技巧:用 PDF 阅读器量取目标位置的横向、纵向百分比,减去基点即为偏移量。
*    文本 / Word 页的排版参数在 js/loaders.js 的 TEXT_LAYOUT（760×1075,左边距 56/760≈7.4%）。
* 8. offlineVoice（V0.3.0）:离线语音文件兑底。浏览器不能朗读（无引擎 / 无中文语音包 /
*    发不出声）时,页面会自动改播这里的音频文件,并自动禁用声音模板（音色固定）。
*    音频由 tools/gen_voice_files.py 预生成,**改了文案或增删触点后必须重新生成**。
*    ★ 最省事的方式（V0.3.1）:双击项目根目录的 gen_voice_oneclick.pyw,
*      它会自动读取本文件 → 比对已有音频 → 只补做/重做变动的那几条,几秒完成；
*      也可以在命令行分两步手动执行:
*        node tools/export_voice_manifest.mjs      （或 python tools/narration_manifest.py）
*        python tools/gen_voice_files.py
* 9. 图片文件解说（V0.4.0）:**图片和 PDF 一样能逐页解说**,只需把 type 设为 "image",
*    并给每一页写 src 指定图片文件即可,其余规则完全通用（触点定位、弹窗、朗读、
*    自动巡讲、离线音频,连音频文件名规则也一样）:
*      { id: "photo", type: "image", name: "现场照片", basePoint: { x: 0.5, y: 0.5 },
*        pages: [ { src: "file/photo-1.jpg", hotspots: [ ... ] },
*                 { src: "file/photo-2.jpg", hotspots: [ ... ] } ] }
*    页码 = pages 下标 + 1,翻页即换图；图片按容器宽度自适应缩放,触点用页面
*    比例坐标定位,因此手机与电脑上的位置一致（建议 basePoint 取图片中心 0.5,0.5）。
* ============================================================ */
